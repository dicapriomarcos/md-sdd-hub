const LANGS = ['es', 'en'];
const norm = (l) => (LANGS.includes(l) ? l : 'es');

function tr(lang, key, vars) {
  const s = (M[norm(lang)] && M[norm(lang)][key]) || M.es[key];
  if (s == null) return key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : '')) : s;
}

module.exports = { tr, LANGS, norm };
